-- 1. Word classification dataset (read-only for all authenticated users)
-- A word can have one row PER AXIS (গঠন / অর্থ / উৎপত্তি) since those are
-- independent facts about the same word (e.g. 'পাঞ্জাবি' is both a রূঢ়ি
-- word on the অর্থ axis AND a ফারসি loanword on the উৎপত্তি axis). Within
-- one axis a word has exactly one sub_group, hence the unique(word, axis).
create table if not exists public.word_classifications (
  id serial primary key,
  word text not null,
  axis text not null check (axis in ('গঠন', 'অর্থ', 'উৎপত্তি')),
  sub_group text not null,
  origin_language text,
  unique (word, axis)
);

